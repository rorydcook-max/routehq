// Writes app/(rove)/rove/[locale]/_components/icon-paths.ts: the Tabler icons rove.rent uses, as the SVG outlines the
// Tabler webfont is drawn from (same version as @tabler/icons-webfont), so the inline icons look exactly as the 493 KB
// font's glyphs did (task perf, 8 Nov 2026). To add an icon: add its Tabler name below and run `node scripts/rove-icons.mjs`.
import { readFileSync, writeFileSync } from "node:fs";

const NAMES = [
  "adjustments-horizontal", "book-2", "building-store", "calendar", "calendar-event", "calendar-repeat", "car", "car-off",
  "chevron-up", "circle-check", "engine", "info-circle", "manual-gearbox", "map-2", "map-pin", "menu-2", "message-circle",
  "motorbike", "receipt-off", "search", "shield-check", "truck-delivery", "users", "world",
  // rove-design-2 (8 Nov 2026): features, trust signals and links.
  "arrow-right", "discount", "file-text", "key", "lock", "photo", "signature", "star"
];

const { version } = JSON.parse(readFileSync(new URL("../node_modules/@tabler/icons-webfont/package.json", import.meta.url), "utf8"));
const camel = (name) => "ti" + name.replace(/(^|-)([a-z0-9])/g, (_, __, c) => c.toUpperCase());

const consts = [];
for (const name of NAMES) {
  const response = await fetch(`https://unpkg.com/@tabler/icons@${version}/icons/outline/${name}.svg`);
  if (!response.ok) throw new Error(`No Tabler icon called ${name} (${response.status})`);
  const svg = await response.text();
  const shapes = svg.replace(/<svg[\s\S]*?>|<\/svg>/g, "").trim();
  const paths = [...shapes.matchAll(/<path\b([^>]*)\/>/g)].filter((match) => !/stroke="none"/.test(match[1])).map((match) => /\sd="([^"]+)"/.exec(match[1])[1]);
  // Only plain stroked paths, so they join into one: anything else would need its own element.
  if (shapes.replace(/<path\b[^>]*\/>/g, "").trim()) throw new Error(`${name} has shapes other than paths`);
  consts.push(`export const ${camel(name)} = "${paths.join(" ")}";`);
}
const map = NAMES.map((name) => `  "${name}": ${camel(name)}`);
writeFileSync(
  new URL("../app/(rove)/rove/[locale]/_components/icon-paths.ts", import.meta.url),
  `// Generated by scripts/rove-icons.mjs from @tabler/icons ${version} (outline, 24 x 24, stroke 2). Don't edit by hand.\n// One export per icon (client components import just the ones they draw), and the map by Tabler name.\n${consts.join("\n")}\n\nexport const ICON_PATHS = {\n${map.join(",\n")}\n} as const;\n\nexport type IconName = keyof typeof ICON_PATHS;\n`
);
console.log(`Wrote ${NAMES.length} icons from @tabler/icons ${version}`);

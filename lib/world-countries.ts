export const WORLD_COUNTRIES: WorldCountry[] = DATA.trim()
  .split("\n")
  .map((line) => {
    const [code, currency, unit, dateOrder, firstDay, zones] = line.split(" ");
    return { code, currency, unit: unit as "km" | "mi", dateOrder: dateOrder as WorldCountry["dateOrder"], firstDay: Number(firstDay), zones: zones.split(",") };
  });

const BY_CODE = new Map(WORLD_COUNTRIES.map((country) => [country.code, country]));

export function worldCountry(code: string): WorldCountry | null {
  return BY_CODE.get(String(code || "").toUpperCase()) || null;
}
